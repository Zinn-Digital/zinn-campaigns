	'init',
	static function (): void {
		load_plugin_textdomain( 'zinn-campaigns', false, dirname( plugin_basename( ZINN_CAMPAIGNS_FILE ) ) . '/languages' );
		Zinn_Campaigns_Forms::register();
		Zinn_Campaigns_Store_Events::register();
		if ( is_admin() ) {
			Zinn_Campaigns_Connect::register();
			Zinn_Campaigns_Admin::register();
		}
	},
	5
);
